// Speed benchmarks: each program in this folder run on CPython and on this
// runtime's builds, best of a few runs, with the output checked against
// CPython's.
//
//   node tests/bench/run.mjs                 CPython and the JavaScript build
//   node tests/bench/run.mjs --go --python   also the Go and Python builds
//   node tests/bench/run.mjs --runs=5        best of 5 (default 3)
//
// Writes docs/BENCHMARKS.md.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { runPython } from "../../js/index.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, "../..");
const argv = process.argv.slice(2);
const args = new Set(argv);
const runs = Number((argv.find((a) => a.startsWith("--runs=")) || "--runs=3").slice(7));

function best(fn) {
  let out = null;
  let ms = Infinity;
  for (let i = 0; i < runs; i++) {
    const t0 = process.hrtime.bigint();
    out = fn();
    ms = Math.min(ms, Number(process.hrtime.bigint() - t0) / 1e6);
  }
  return { out, ms };
}

function cli(cmd, cmdArgs, file) {
  const out = fs.mkdtempSync(path.join(os.tmpdir(), "pybench-"));
  const r = spawnSync(cmd, [...cmdArgs, file, out], { encoding: "utf8", timeout: 600000 });
  fs.rmSync(out, { recursive: true, force: true });
  return (r.stdout || "").split("\n").filter((l) => !l.startsWith("[wrote ")).join("\n") + (r.status === 0 ? "" : "error: " + (r.stderr || "killed").trim().split("\n").pop());
}

const targets = [
  ["CPython", (f) => cli("python3", [], f)],
  ["JavaScript", (f) => {
    const r = runPython(fs.readFileSync(f, "utf8"), { maxSteps: 2_000_000_000 });
    return r.stdout + (r.ok ? "" : "error: " + r.traceback.trim().split("\n").pop());
  }],
];
if (args.has("--go")) targets.push(["Go", (f) => cli(path.join(REPO, "build/go/pyrun"), [], f)]);
if (args.has("--rust")) targets.push(["Rust", (f) => cli(path.join(REPO, "build/rust/pyrun"), [], f)]);
if (args.has("--rpy")) targets.push(["Rust (hand-written)", (f) => cli(path.join(REPO, "rust/target/release/rpy"), [], f)]);
if (args.has("--python")) targets.push(["Python", (f) => cli("python3", [path.join(REPO, "build/python/pyrun.py")], f)]);

const files = fs.readdirSync(HERE).filter((f) => f.endsWith(".py")).sort();
const rows = [];
for (const f of files) {
  const file = path.join(HERE, f);
  const row = { name: f.replace(/\.py$/, ""), res: {} };
  for (const [t, run] of targets) row.res[t] = best(() => run(file));
  const want = row.res.CPython.out;
  for (const [t] of targets) row.res[t].ok = row.res[t].out === want;
  rows.push(row);
  console.log(row.name.padEnd(10) + targets.map(([t]) => `${t} ${row.res[t].ms.toFixed(0)} ms${row.res[t].ok ? "" : " (wrong output)"}`).join("  "));
}

const tn = targets.map(([t]) => t);
let md = `# Speed benchmarks

Generated by \`node tests/bench/run.mjs${argv.filter((a) => a === "--go" || a === "--rust" || a === "--python").map((a) => " " + a).join("")}\` — do not edit.

Each program in tests/bench is run ${runs} times per target and the best
wall-clock time is kept. The JavaScript build runs in-process, so its time
has no start-up cost; the others are timed as whole processes. "x CPython"
is the time relative to CPython; a mark means the output differed from
CPython's.

| program | ${tn.map((t) => t + (t === "CPython" ? " ms" : " ms | x CPython")).join(" | ")} |
|---|${tn.map((t) => (t === "CPython" ? "---:" : "---:|---:")).join("|")}|
`;
for (const r of rows) {
  const base = r.res.CPython.ms;
  md += `| ${r.name} | ${tn.map((t) => {
    const x = r.res[t];
    const ms = x.ms.toFixed(0) + (x.ok ? "" : " ✗");
    return t === "CPython" ? ms : `${ms} | ${(x.ms / base).toFixed(1)}`;
  }).join(" | ")} |\n`;
}
const cpy = spawnSync("python3", ["--version"], { encoding: "utf8" }).stdout.trim();
md += `\nCPython: ${cpy}; Node ${process.version}; ${os.cpus()[0]?.model || "unknown CPU"}.\n`;
fs.writeFileSync(path.join(REPO, "docs/BENCHMARKS.md"), md);
console.log("report in docs/BENCHMARKS.md");
