// Feature matrix: small programs, one per Python feature, run on this
// runtime and compared with CPython's output.
//
//   node tests/features/run.mjs                 the JavaScript build; writes
//                                               docs/FEATURES.md
//   node tests/features/run.mjs --go --python   also the Go and Python builds
//   node tests/features/run.mjs --record        record CPython's output in
//                                               expected.json (needs python3)
//
// A feature is supported on a target when the program prints exactly what
// CPython prints. Uncaught errors count as output: their last line is kept.
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { spawnSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { runPython } from "../../js/index.mjs";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, "../..");
const args = new Set(process.argv.slice(2));

export function loadCases() {
  const text = fs.readFileSync(path.join(HERE, "cases.txt"), "utf8");
  const cases = [];
  let cur = null;
  for (const line of text.split("\n")) {
    const m = /^### (.+?) \| (.+)$/.exec(line);
    if (m) {
      cur = { category: m[1].trim(), name: m[2].trim(), code: [] };
      cases.push(cur);
    } else if (cur) cur.code.push(line);
  }
  for (const c of cases) c.code = c.code.join("\n").replace(/\s+$/, "") + "\n";
  return cases;
}

const key = (c) => `${c.category} | ${c.name}`;
const lastLine = (s) => s.trim().split("\n").pop() || "";

function runCPython(c) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "pyfeat-"));
  fs.writeFileSync(path.join(dir, "main.py"), c.code);
  const r = spawnSync("python3", ["main.py"], { cwd: dir, encoding: "utf8" });
  fs.rmSync(dir, { recursive: true, force: true });
  return r.stdout + (r.status === 0 ? "" : "error: " + lastLine(r.stderr) + "\n");
}

function runJs(c) {
  const r = runPython(c.code, { maxSteps: 50_000_000 });
  return r.stdout + (r.ok ? "" : "error: " + lastLine(r.traceback) + "\n");
}

function runCli(cmd, cmdArgs, c) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "pyfeat-"));
  fs.writeFileSync(path.join(dir, "main.py"), c.code);
  const out = path.join(dir, "out");
  fs.mkdirSync(out);
  const r = spawnSync(cmd, [...cmdArgs, path.join(dir, "main.py"), out], { encoding: "utf8", timeout: 60000 });
  fs.rmSync(dir, { recursive: true, force: true });
  // the command line builds print uncaught errors as a traceback on stderr
  // and note the files they saved; neither is the program's output
  const stdout = (r.stdout || "").split("\n").filter((l) => !l.startsWith("[wrote ")).join("\n");
  return stdout + (r.status === 0 ? "" : "error: " + lastLine(r.stderr || "killed") + "\n");
}

const cases = loadCases();
const expectedFile = path.join(HERE, "expected.json");

if (args.has("--record")) {
  const version = spawnSync("python3", ["--version"], { encoding: "utf8" }).stdout.trim();
  const expected = { cpython: version, cases: {} };
  for (const c of cases) expected.cases[key(c)] = runCPython(c);
  fs.writeFileSync(expectedFile, JSON.stringify(expected, null, 1) + "\n");
  console.log(`recorded ${cases.length} features from ${version}`);
  process.exit(0);
}

const expected = JSON.parse(fs.readFileSync(expectedFile, "utf8"));
const targets = [["JavaScript", runJs]];
if (args.has("--go")) targets.push(["Go", (c) => runCli(path.join(REPO, "build/go/pyrun"), [], c)]);
if (args.has("--rust")) targets.push(["Rust", (c) => runCli(path.join(REPO, "build/rust/pyrun"), [], c)]);
if (args.has("--python")) targets.push(["Python", (c) => runCli("python3", [path.join(REPO, "build/python/pyrun.py")], c)]);

const results = [];
for (const c of cases) {
  const want = expected.cases[key(c)];
  if (want === undefined) throw new Error(`no expected output for "${key(c)}": run with --record`);
  const row = { ...c, want, got: {} };
  for (const [t, run] of targets) {
    const got = run(c);
    let note = "";
    if (got !== want) {
      const a = want.split("\n");
      const b = got.split("\n");
      const i = a.findIndex((l, k) => l !== b[k]);
      note = b[i] && b[i].startsWith("error: ") ? b[i].slice(7) : `line ${i + 1}: got ${JSON.stringify((b[i] || "").slice(0, 90))}`;
    }
    row.got[t] = { ok: got === want, note };
  }
  results.push(row);
  const marks = targets.map(([t]) => (row.got[t].ok ? "ok  " : "FAIL") + " " + t).join("  ");
  console.log(`${marks}  ${key(c)}${row.got.JavaScript.ok ? "" : "  — " + row.got.JavaScript.note}`);
}
writeReport(results, targets.map(([t]) => t), expected.cpython);

function writeReport(rows, tnames, cpython) {
  const cats = [...new Set(rows.map((r) => r.category))];
  const total = (t) => rows.filter((r) => r.got[t].ok).length;
  let md = `# Python feature matrix

Generated by \`node tests/features/run.mjs${tnames.length > 1 ? " --go --python" : ""}\` — do not edit.

Each feature is a short program in tests/features/cases.txt. It is
supported on a target when it prints exactly what CPython (${cpython})
prints; a failing one shows the first difference or the error it stopped
with.

| target | features supported |
|---|---:|
${tnames.map((t) => `| ${t} | ${total(t)} of ${rows.length} |`).join("\n")}

`;
  for (const cat of cats) {
    const rs = rows.filter((r) => r.category === cat);
    md += `## ${cat}\n\n| feature | ${tnames.join(" | ")} | note |\n|---|${tnames.map(() => ":---:").join("|")}|---|\n`;
    for (const r of rs) {
      const note = tnames.map((t) => r.got[t].note).find((n) => n) || "";
      md += `| ${r.name} | ${tnames.map((t) => (r.got[t].ok ? "yes" : "no")).join(" | ")} | ${note.replace(/\|/g, "\\|").replace(/\n/g, " ").slice(0, 110)} |\n`;
    }
    md += "\n";
  }
  fs.mkdirSync(path.join(REPO, "docs"), { recursive: true });
  fs.writeFileSync(path.join(REPO, "docs/FEATURES.md"), md);
  console.log(`\n${tnames.map((t) => `${t}: ${total(t)} of ${rows.length}`).join(", ")}; report in docs/FEATURES.md`);
}
