print(s.mean(), s.median(), s.std(), s.min(), s.max(), s.sum())
print(s.rolling(3).mean())
print(s.pct_change())
print(s.rank())
print(s.nlargest(3))
print(s.unique(), s.unique().tolist(), s.nunique())
print(s.map({1: "one", 3: "three"}))
print(s.apply(lambda v: v ** 2))
print(s.isin([1, 9]))
print(s.between(2, 5))
print(s.quantile(0.9))
