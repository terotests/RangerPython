import pandas as pd
pd.set_option("future.infer_string", False)
left = pd.DataFrame({"id": [1, 2, 3, 4], "name": ["Ann", "Bob", "Cid", "Dee"], "dept": ["x", "y", "x", "z"]})
right = pd.DataFrame({"id": [2, 3, 5], "salary": [5000, 6200, 4100]})
print(pd.merge(left, right, on="id"))
print(left.merge(right, on="id", how="left"))
print(left.merge(right, on="id", how="outer"))
print(left.merge(right, on="id", how="right"))
depts = pd.DataFrame({"dept": ["x", "y"], "dname": ["Sales", "Ops"]})
print(left.merge(depts, on="dept", how="left"))
a = pd.DataFrame({"k": [1, 2], "v": [10, 20]})
b = pd.DataFrame({"k": [1, 2], "v": [30, 40]})
print(a.merge(b, on="k"))
print(pd.concat([a, b]))
print(pd.concat([a, b], ignore_index=True))
sales = pd.DataFrame({
    "region": ["N", "N", "S", "S", "N", "S"],
    "quarter": ["Q1", "Q2", "Q1", "Q2", "Q1", "Q1"],
    "amount": [10.0, 12.5, 7.0, 9.0, 3.0, 1.0],
})
print(sales.pivot_table(values="amount", index="region", columns="quarter", aggfunc="sum"))
print(sales.pivot_table(values="amount", index="region", columns="quarter", aggfunc="sum", fill_value=0))
print(sales.pivot_table(index="region", values="amount", aggfunc="mean"))
print(sales.pivot_table(values="amount", index="region", columns="quarter", aggfunc="sum", margins=True))
