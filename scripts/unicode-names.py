# \N{...} escapes and unicodedata.name()/lookup(). Run with CPython:
#   python3 scripts/unicode-names.py
import unicodedata, pathlib

BLOCKS = [
    (0x20, 0x7E), (0xA0, 0x24F), (0x370, 0x3FF), (0x400, 0x4FF),
    (0x2000, 0x206F), (0x20A0, 0x20C0), (0x2100, 0x214F), (0x2190, 0x21FF),
    (0x2200, 0x22FF), (0x2500, 0x25FF), (0x2600, 0x26FF),
    (0x3000, 0x303F), (0xFE00, 0xFE0F), (0xFFF0, 0xFFFD),
]
parts = []
for lo, hi in BLOCKS:
    for cp in range(lo, hi + 1):
        name = unicodedata.name(chr(cp), "")
        if name:
            parts.append("%s=%X" % (name, cp))
table = ";" + ";".join(parts) + ";"
out = """; SPDX-License-Identifier: MIT
; Generated by scripts/unicode-names.py (Unicode %s) — do not edit.

class PyUnicodeNames {
    sfn table:string () {
        return "%s"
    }

    ; the code point of a name, -1 when the table does not have it
    sfn lookup:int (name:string) {
        def t:string (PyUnicodeNames.table())
        def key:string (";" + (to_uppercase name) + "=")
        def at:int (indexOf t key)
        if (at < 0) {
            return -1
        }
        def from:int (at + (strlen key))
        def rest:string (substring t from (from + 8))
        def hex:string (substring rest 0 (indexOf rest ";"))
        def v:int 0
        def cs:[int] (to_chars hex)
        for cs c:int i {
            if ((c >= 48) && (c <= 57)) {
                v = (v * 16) + (c - 48)
            } {
                v = (v * 16) + (c - 55)
            }
        }
        return v
    }

    ; the name of a code point, "" when the table does not have it
    sfn name:string (cp:int) {
        def t:string (PyUnicodeNames.table())
        def digits:string "0123456789ABCDEF"
        def hex:string ""
        def v:int cp
        if (v == 0) {
            hex = "0"
        }
        while (v > 0) {
            def d:int (v %% 16)
            hex = ((substring digits d (d + 1)) + hex)
            v = (idiv (v - d) 16)
        }
        def key:string ("=" + hex + ";")
        def at:int (indexOf t key)
        if (at < 0) {
            return ""
        }
        def start:int at
        while ((start > 0) && ((substring t (start - 1) start) != ";")) {
            start = start - 1
        }
        return (substring t start at)
    }
}
""" % (unicodedata.unidata_version, table)
pathlib.Path(__file__).resolve().parent.parent.joinpath("src", "PyUnicodeNames.rgr").write_text(out)
print(len(parts), "names,", len(table), "bytes")
