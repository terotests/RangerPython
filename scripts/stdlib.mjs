// Writes src/PyStdlib.rgr: the modules in lib/ written in Python, kept in
// the runtime as source and run on first import (after the working folder
// and the search path, so a script's own module of the same name wins).
import fs from "node:fs";
import path from "node:path";
import { REPO } from "./compiler.mjs";

export function writeStdlib() {
  const lib = path.join(REPO, "lib");
  const mods = [];
  const walk = (dir) => {
    for (const ent of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
      const full = path.join(dir, ent.name);
      if (ent.isDirectory()) walk(full);
      else if (ent.name.endsWith(".py")) {
        let name = path.relative(lib, full).slice(0, -3).split(path.sep).join(".");
        let pkg = false;
        if (name.endsWith(".__init__") || name === "__init__") {
          name = name.replace(/\.?__init__$/, "");
          pkg = true;
        }
        mods.push({ name, pkg, src: fs.readFileSync(full, "utf8").replace(/\r\n?/g, "\n") });
      }
    }
  };
  walk(lib);
  const esc = (s) => s.replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\n/g, "\\n").replace(/\t/g, "\\t");
  let out = `; SPDX-License-Identifier: MIT
; Generated by scripts/stdlib.mjs from lib/ — do not edit.

class PyStdlib {
    ; the source of a module in lib/, or none
    sfn source@(optional):string (name:string) {
        def none@(optional):string
`;
  for (const m of mods) {
    out += `        if (name == "${m.name}") {\n            def s${mods.indexOf(m)}@(optional):string "${esc(m.src)}"\n            return s${mods.indexOf(m)}\n        }\n`;
  }
  out += `        return none
    }

    sfn isPackage:boolean (name:string) {
`;
  for (const m of mods.filter((m) => m.pkg)) out += `        if (name == "${m.name}") {\n            return true\n        }\n`;
  out += `        return false
    }
}
`;
  fs.writeFileSync(path.join(REPO, "src/PyStdlib.rgr"), out);
  return mods.map((m) => m.name);
}

if (process.argv[1] && import.meta.url.endsWith(path.basename(process.argv[1]))) {
  console.log("lib modules:", writeStdlib().join(" "));
}
